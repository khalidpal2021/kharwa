-- ---------------------------------------------------------- qada_backlog -----

-- Prayers owed from before using Kharwa, entered by hand: one row per person
-- per prayer, upserted on (person, prayer). Witr is included since it is
-- wajib in the Hanafi school, though it is not tracked day to day.
create table if not exists public.qada_backlog (
  person     text        not null references public.people (id) on delete cascade,
  prayer     text        not null check (prayer in ('fajr', 'dhuhr', 'asr', 'maghrib', 'isha', 'witr')),
  count      integer     not null default 0 check (count >= 0),
  updated_at timestamptz not null default now(),
  primary key (person, prayer)
);

drop trigger if exists qada_backlog_touch_updated_at on public.qada_backlog;
create trigger qada_backlog_touch_updated_at
  before update on public.qada_backlog
  for each row execute function public.touch_updated_at();

-- ---------------------------------------------------- push_subscriptions -----

-- Prayer reminders: one row per device that has turned them on, so a person
-- can have several. `keys` is the browser's { p256dh, auth }; `settings` is
-- { prayers: [...], minutes_before: 0 | 5 | 10 | 15 }. The send-reminders Edge
-- Function reads these every minute, and `last_sent` ("2026-10-09:asr") stops
-- a reminder going out twice. Upserted on endpoint.
create table if not exists public.push_subscriptions (
  id         bigint generated by default as identity primary key,
  person     text        not null references public.people (id) on delete cascade,
  endpoint   text        not null,
  keys       jsonb       not null,
  settings   jsonb       not null
             default '{"prayers": ["fajr", "dhuhr", "asr", "maghrib", "isha"], "minutes_before": 0}'::jsonb,
  last_sent  text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.push_subscriptions'::regclass
      and conname  = 'push_subscriptions_endpoint_key'
  ) then
    alter table public.push_subscriptions
      add constraint push_subscriptions_endpoint_key unique (endpoint);
  end if;
end $$;

create index if not exists push_subscriptions_person_idx
  on public.push_subscriptions (person);

drop trigger if exists push_subscriptions_touch_updated_at on public.push_subscriptions;
create trigger push_subscriptions_touch_updated_at
  before update on public.push_subscriptions
  for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------- nudges -----

-- One row per nudge sent: "pray Isha", from one of you to the other. Written
-- by the send-nudge Edge Function, which allows one per prayer per direction
-- every 15 minutes; the app reads today's to show "nudged 3m ago".
create table if not exists public.nudges (
  id          bigint generated by default as identity primary key,
  from_person text        not null references public.people (id) on delete cascade,
  to_person   text        not null references public.people (id) on delete cascade,
  prayer      text        not null check (prayer in ('fajr', 'dhuhr', 'asr', 'maghrib', 'isha')),
  log_date    date        not null,
  sent_at     timestamptz not null default now()
);

create index if not exists nudges_pair_day_idx
  on public.nudges (from_person, to_person, log_date, prayer, sent_at desc);

-- -------------------------------------------------------------- messages -----

-- The Us tab: messages between the two of you. `body` is the text, or for a
-- shared ayah or hadith its translation; `ref` says what was shared
-- ({ surah, ayah, ayah_to, name, arabic } or { book, number, name }), or for
-- a nudge { prayer, date }. A 'mood' message ("I'm stressed") has the mood's
-- id in `body`. Written by the send-message Edge Function (and
-- send-nudge for nudges); deleted after 30 days by the job in
-- supabase/messages-cron.sql.
create table if not exists public.messages (
  id          bigint generated by default as identity primary key,
  from_person text        not null references public.people (id) on delete cascade,
  to_person   text        not null references public.people (id) on delete cascade,
  type        text        not null check (type in ('text', 'ayah', 'hadith', 'nudge')),
  body        text        not null default '' check (char_length(body) <= 6000),
  ref         jsonb,
  note        text        check (char_length(note) <= 300),
  created_at  timestamptz not null default now(),
  read_at     timestamptz
);

-- 'mood' came later: the check is replaced, so re-running keeps it current.
alter table public.messages drop constraint if exists messages_type_check;
alter table public.messages add constraint messages_type_check
  check (type in ('text', 'ayah', 'hadith', 'nudge', 'mood'));

create index if not exists messages_created_idx
  on public.messages (created_at);

create index if not exists messages_to_unread_idx
  on public.messages (to_person, created_at) where read_at is null;

-- Realtime UPDATE and DELETE events carry the whole row, so "Seen" and a
-- deleted message reach the other phone.
alter table public.messages replica identity full;

-- ------------------------------------------------------------ us_presets -----

-- Ayahs either of you added to a mood in "Ayahs for the moment", from the
-- Quran tab. Shown to both, after the built-in ones in js/us-presets.js.
create table if not exists public.us_presets (
  id         bigint generated by default as identity primary key,
  person     text        not null references public.people (id) on delete cascade,
  mood       text        not null check (mood ~ '^[a-z]{1,24}$'),
  surah      smallint    not null check (surah between 1 and 114),
  ayah_from  smallint    not null check (ayah_from between 1 and 286),
  ayah_to    smallint    not null check (ayah_to between 1 and 286),
  created_at timestamptz not null default now(),
  check (ayah_to >= ayah_from)
);

-- One of each per mood, whoever added it. Named so that the client can
-- upsert with on_conflict=mood,surah,ayah_from,ayah_to.
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.us_presets'::regclass
      and conname  = 'us_presets_mood_surah_ayah_from_ayah_to_key'
  ) then
    alter table public.us_presets
      add constraint us_presets_mood_surah_ayah_from_ayah_to_key
      unique (mood, surah, ayah_from, ayah_to);
  end if;
end $$;

